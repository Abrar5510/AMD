"""How much model error can the rule engine absorb? A simulated stress test, no GPU, no footage.

The fake world from tests/test_coach.py, made unreliable on purpose: SigLIP thinks a frame shows a random step
25% of the time, and Gemma is *confidently* wrong (started and done both flipped, confidence 0.6-1.0) at the
given rate. Each row replays clean runs and skip-step-4 runs through the real Coach.

    python -m scripts.sim_eval            # writes eval/sim_results.md
    python -m scripts.sim_eval --runs 50  # quicker

This measures the rule engine's design, not Gemma: the real numbers come from scripts/run_eval.py on filmed runs.
"""
import argparse
import json
import random
from pathlib import Path

import numpy as np

from dataclasses import replace

from app.coach import Config
from tests.test_coach import IDS, fake_embed, kinds, run

GEMMA_S = 0.6        # simulated Gemma round trip, roughly 12B on one MI300X
SIGLIP_NOISE = 0.25
SKIP4 = [1, 2, 3, 5, 6, 7, 8]
ERROR_T = 3 * 3.0    # trainee starts step 5 here (3 steps x 3 s)


def noisy(rng, gemma_err):
    def embed(jpegs):
        if rng.random() < SIGLIP_NOISE:
            return np.eye(len(IDS), dtype=np.float32)[[rng.randrange(len(IDS))]]
        return fake_embed(jpegs)

    def verify(procedure, sid, frames, keyframe):
        now = json.loads(frames[-1])
        started, done = sid == now["doing"] or sid in now["done"], sid in now["done"]
        if rng.random() < gemma_err:
            return {"observed": "", "started": not started, "done": not done, "confidence": rng.uniform(0.6, 1.0)}, GEMMA_S
        return {"observed": "", "started": started, "done": done, "confidence": 0.9}, GEMMA_S
    return embed, verify


def row(gemma_err, n, seed, cfg):
    rng = random.Random(seed)
    false_alarm_runs = 0
    for _ in range(n):
        embed, verify = noisy(rng, gemma_err)
        _, events = run(IDS, verify=verify, cfg=cfg, embed=embed)
        false_alarm_runs += bool(kinds(events, "interrupt"))
    caught, lat, wrong = 0, [], 0
    for _ in range(n):
        embed, verify = noisy(rng, gemma_err)
        _, events = run(SKIP4, verify=verify, cfg=cfg, embed=embed)
        stops = kinds(events, "interrupt")
        hit = next((e for e in stops if e.step == 4 and e.t >= ERROR_T - 1), None)
        wrong += any(e.step != 4 or e.t < ERROR_T - 1 for e in stops)
        if hit:
            caught += 1
            lat.append(hit.t + hit.secs - ERROR_T)
    lat.sort()
    pct = lambda q: f"{lat[min(len(lat) - 1, int(q * len(lat)))]:.1f}" if lat else "-"
    return (f"| {gemma_err:.0%} | {caught}/{n} ({caught / n:.0%}) | {pct(0.5)} s | {pct(0.95)} s | "
            f"{false_alarm_runs}/{n} ({false_alarm_runs / n:.0%}) | {wrong}/{n} |")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--runs", type=int, default=200, help="clean runs and skip-4 runs per row")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--out", default="eval/sim_results.md")
    args = p.parse_args()
    cfg = Config.from_env()
    lines = [f"# Rule engine under a bad model (simulation)\n",
             f"{args.runs} clean + {args.runs} skip-step-4 runs per row. SigLIP wrong on {SIGLIP_NOISE:.0%} of frames; "
             f"Gemma confidently wrong at the row's rate; {GEMMA_S * 1000:.0f} ms per Gemma call; config {cfg}.\n",
             "Generated by `python -m scripts.sim_eval`. A design check, not a model measurement: see `run_eval.py` for filmed runs."]
    for title, c in [(f"Ghost Expert rule engine (confirm={cfg.confirm})", cfg),
                     ("Baseline: one Gemma answer decides (confirm=1)", replace(cfg, confirm=1))]:
        lines += [f"\n## {title}\n",
                  "| Gemma wrong | Skip-4 caught | Latency p50 | Latency p95 | Clean runs with a false stop | Skip-4 runs with a wrong stop |",
                  "|---|---|---|---|---|---|"]
        print(title)
        for i, err in enumerate([0.0, 0.05, 0.10, 0.20]):
            lines.append(row(err, args.runs, args.seed + i, c))
            print(lines[-1], flush=True)
    Path(args.out).parent.mkdir(exist_ok=True)
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
